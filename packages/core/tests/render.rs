#[test]
fn decay_count_and_lines_feed_render() {
    let d = tmpdir("decay");
    let mut st = State::default();
    let mut y = plain(Kind::Y, "Y-01", "active");
    y.title = "Note".to_string();
    reflist(&mut y, "surface", &["src/dead.jl", "src/live.jl"]);
    reflist(&mut y, "tags", &["auth", "lost"]);
    put(&mut st, y);
    put(&mut st, plain(Kind::D, "D-01", "accepted"));
    edge(&mut st, "Y-01", "distills", "D-01");
    st.edges.last_mut().unwrap().t_created = Some("2031-01-01T00:00:00Z".to_string());
    let ctx = CliCtx::new(d.to_string_lossy().into_owned());
    std::fs::create_dir_all(ctx.devdir()).unwrap();
    std::fs::write(
        ctx.glossarypath(),
        format!("{INIT_GLOSSARY}| auth | a term | test |\n"),
    )
    .unwrap();
    std::fs::create_dir_all(d.join("src")).unwrap();
    std::fs::write(d.join("src/live.jl"), "live\n").unwrap();
    atomic_write_same_dir(&ctx.lockpath(), &serialize(&st)).unwrap();
    let st = match load(&ctx, true) {
        Ok(s) => s,
        Err(e) => panic!("load failed: code={} err={}", e.code, e.err),
    };
    assert_eq!(dashboard_decay_count(&ctx, &st), 1);
    let errs = discovery_decay_errors(&st, &ctx.root, &ctx.glossarypath());
    assert_eq!(
        errs,
        vec![
            "decay: Y-01 dead surface: src/dead.jl".to_string(),
            "decay: Y-01 lost glossary term: lost".to_string(),
        ]
    );
    let idx = render_index(&st, 1);
    assert!(idx.contains("| Decay | 1 | Discovery with decay signals |"));
}

