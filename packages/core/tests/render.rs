#[test]
fn decay_rotted_origin_lines() {
    let mut st = State::default();
    let mut y = plain(Kind::Y, "Y-01", "active");
    y.title = "Note".to_string();
    put(&mut st, y);
    put(&mut st, plain(Kind::D, "D-01", "superseded"));
    put(&mut st, plain(Kind::B, "B-01", "invalidated_blocking"));
    edge(&mut st, "Y-01", "distills", "D-01");
    edge(&mut st, "Y-01", "distills", "B-01");
    let d = tmpdir("rotted");
    let gpath = d.join("glossary.md");
    let errs = discovery_decay_errors(&st, &d.to_string_lossy(), &gpath);
    assert_eq!(
        errs,
        vec![
            "decay: Y-01 rotted origin: D-01 (superseded)".to_string(),
            "decay: Y-01 rotted origin: B-01 (invalidated_blocking)".to_string(),
        ]
    );
}

#[test]
fn cmd_render_writes_index_bytes() {
    let d = tmpdir("cmd-render");
    let ctx = CliCtx::new(d.to_string_lossy().into_owned());
    std::fs::create_dir_all(ctx.devdir()).unwrap();
    let mut st = State::default();
    let mut g = plain(Kind::G, "G-01", "unverified");
    g.title = "Ship".to_string();
    put(&mut st, g);
    atomic_write_same_dir(&ctx.lockpath(), &serialize(&st)).unwrap();
    let r = cmd_render(&ctx, &[], &[]);
    assert_eq!(r.code, EXIT_OK);
    let st2 = load(&ctx, true).ok().expect("load failed");
    let bytes = std::fs::read_to_string(ctx.indexpath()).unwrap();
    assert_eq!(bytes, render_index(&st2, 0));
}
